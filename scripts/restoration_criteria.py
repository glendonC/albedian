"""The acceptance criteria of the restoration spec, read from its requirements: the closed list a media record's
basis cites ("Required by REQ-RST-{criterion}.", design section 14).

Writes the list into `services/contracts/media.py` and `packages/contracts/src/media.ts`, between their generated
markers. With `--check` it changes nothing and exits 1 when either file's list differs from the spec; the contract
test `tests/integration/test_media_contract.py` runs the same check.
Run from the repository root: uv run python scripts/restoration_criteria.py [--check]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / ".kiro" / "specs" / "restoration-for-every-upload" / "requirements.md"
TARGETS = {
    ROOT / "services" / "contracts" / "media.py": (
        "# Generated by scripts/restoration_criteria.py from the restoration spec's requirements; do not edit by hand\n",
        "# End of the generated list\n",
    ),
    ROOT / "packages" / "contracts" / "src" / "media.ts": (
        "// Generated by scripts/restoration_criteria.py from the restoration spec's requirements; do not edit by hand\n",
        "// End of the generated list\n",
    ),
}
_REQUIREMENT = re.compile(r"^### REQ-RST-([0-9]+):")
_CRITERION = re.compile(r"^  ([0-9]+)\. ")


def criteria(text: str) -> list[str]:
    """Every acceptance criterion of the spec's Requirements section, as "requirement.criterion", in order. The
    requirements and each one's criteria must run 1, 2, 3 and so on, so a renumbering or a stray list is caught."""
    lines = text.splitlines()
    start = lines.index("## Requirements")
    found: list[str] = []
    requirement = 0
    criterion = 0
    for line in lines[start + 1:]:
        if line.startswith("## "):
            break
        heading = _REQUIREMENT.match(line)
        if heading:
            if int(heading.group(1)) != requirement + 1 or (requirement and not criterion):
                raise ValueError(f"REQ-RST-{heading.group(1)} out of order, or REQ-RST-{requirement} has no criteria")
            requirement, criterion = int(heading.group(1)), 0
            continue
        item = _CRITERION.match(line)
        if item and requirement:
            if int(item.group(1)) != criterion + 1:
                raise ValueError(f"REQ-RST-{requirement}.{item.group(1)} out of order")
            criterion = int(item.group(1))
            found.append(f"{requirement}.{criterion}")
    if not found or not criterion:
        raise ValueError("no acceptance criteria found")
    return found


def block(path: Path, values: list[str]) -> str:
    """The generated list as `path`'s language writes it: one line per requirement."""
    rows: dict[str, list[str]] = {}
    for value in values:
        rows.setdefault(value.split(".")[0], []).append(value)
    if path.suffix == ".py":
        body = "".join("    " + " ".join(f'"{value}",' for value in row) + "\n" for row in rows.values())
        return f"RESTORATION_CRITERIA = (\n{body})\n"
    body = "".join("  " + " ".join(f"'{value}'," for value in row) + "\n" for row in rows.values())
    return f"export const RESTORATION_CRITERIA = [\n{body}] as const;\n"


def rewritten(path: Path, values: list[str]) -> str:
    text = path.read_text()
    begin, end = TARGETS[path]
    if text.count(begin) != 1 or text.count(end) != 1 or text.index(end) < text.index(begin):
        raise ValueError(f"{path.name} lacks one pair of generated markers")
    head, rest = text.split(begin)
    _, tail = rest.split(end)
    return head + begin + block(path, values) + end + tail


def differences() -> list[str]:
    """The target files whose list is not the spec's."""
    values = criteria(SPEC.read_text())
    return [str(path.relative_to(ROOT)) for path in TARGETS if rewritten(path, values) != path.read_text()]


def main() -> int:
    if "--check" in sys.argv[1:]:
        stale = differences()
        for name in stale:
            print(f"{name}: the criteria list differs from {SPEC.relative_to(ROOT)}")
        return 1 if stale else 0
    values = criteria(SPEC.read_text())
    for path in TARGETS:
        path.write_text(rewritten(path, values))
    print(f"{len(values)} criteria written to {len(TARGETS)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
